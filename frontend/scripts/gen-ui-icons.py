"""Generates src/canvas/ui-icons.ts from a folder of line icons.

    python scripts/gen-ui-icons.py "<icon folder>"

Each icon-*.svg is a 64x64 drawing; its body (everything but <metadata>) is
kept as-is, made single-colour: every hex colour becomes the item's own
colour (filled shapes fill with it, strokes take the furniture stroke), and
stroke widths are dropped so the plan's line thickness setting applies.
Masks keep their own colours.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HEX = re.compile(r'\s(?:stroke|color)="#[0-9A-Fa-f]{6}"')
FILL_HEX = re.compile(r'fill="#[0-9A-Fa-f]{6}"')
DROP = re.compile(r'\s(?:stroke-width|xmlns)="[^"]*"')
MASK = re.compile(r"(<mask[\s\S]*?</mask>)")


def clean(body: str, name: str) -> str:
    parts = MASK.split(body)
    out = []
    for part in parts:
        if part.startswith("<mask"):
            out.append(part)
            continue
        part = HEX.sub("", part)
        part = FILL_HEX.sub('fill="currentColor"', part)
        part = DROP.sub("", part)
        out.append(part)
    body = "".join(out)
    # Mask ids stay unique per icon.
    body = re.sub(r'id="([^"]+)"', lambda m: f'id="ui-{name}-{m.group(1)}"', body)
    body = re.sub(r"url\(#([^)]+)\)", lambda m: f"url(#ui-{name}-{m.group(1)})", body)
    return re.sub(r"\s+", " ", body).strip()


def main() -> None:
    src = Path(sys.argv[1])
    labels = {}
    manifest = src / "manifest.json"
    if manifest.exists():
        for icon in json.loads(manifest.read_text(encoding="utf-8"))["icons"]:
            labels[icon["name"]] = icon.get("label")
    icons = {}
    for f in sorted(src.glob("icon-*.svg")):
        text = f.read_text(encoding="utf-8")
        inner = re.search(r"<svg[^>]*>([\s\S]*)</svg>", text)
        if not inner:
            continue
        body = re.sub(r"<metadata[\s\S]*?</metadata>", "", inner.group(1))
        name = f.stem[len("icon-") :]
        label = labels.get(f.stem) or name.replace("-", " ").replace("_", " ").capitalize()
        icons[name] = {"label": label, "svg": clean(body, name)}
    out = Path(__file__).resolve().parent.parent / "src" / "canvas" / "ui-icons.ts"
    lines = [
        "/** Generated by scripts/gen-ui-icons.py from a line-icon set — don't",
        " * edit by hand. Each is a 64x64 single-colour",
        " * drawing (see furniture-draw.ts's \"icon\" template). */",
        "",
        "export const UI_ICONS: Record<string, { label: string; svg: string }> = {",
    ]
    for name, icon in icons.items():
        lines.append(f"  {json.dumps(name)}: {{ label: {json.dumps(icon['label'])}, svg: {json.dumps(icon['svg'])} }},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(icons)} icons -> {out}")


if __name__ == "__main__":
    main()
